const getQuestionsForCategory = (cat: string, lessonTitle: string, lessonIndex: number) => {
  const list = AI_QUESTIONS_BY_CATEGORY[cat] || AI_QUESTIONS_BY_CATEGORY["general"];
  
  // Choose reinforcement question
  const rIdx = (lessonIndex * 3) % list.length;
  const rItem = list[rIdx];
  const reinforcement = [{
    question: rItem.q,
    options: rItem.opts,
    correctAnswer: rItem.ans
  }];
  
  // Choose 10 homework questions (cycle with offset to ensure variety)
  const homework = Array.from({ length: 10 }, (_, i) => {
    const qIdx = (lessonIndex * 7 + i) % list.length;
    const item = list[qIdx];
    return {
      question: `${item.q} (Тапсырма №${i + 1})`,
      options: item.opts,
      correctAnswer: item.ans
    };
  });
  
  return { reinforcement, homework };
};

